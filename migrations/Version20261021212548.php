    private function convertSerialToIdentity(string $table, string $type = 'INT'): void
    {
        $this->addSql(\sprintf('ALTER TABLE %s ALTER id DROP DEFAULT', $table));
        $this->addSql(\sprintf('DROP SEQUENCE IF EXISTS %s_id_seq CASCADE', $table));
        $this->addSql(\sprintf('ALTER TABLE %s ALTER id TYPE %s', $table, $type));
        $this->addSql(\sprintf('ALTER TABLE %s ALTER id ADD GENERATED BY DEFAULT AS IDENTITY', $table));
        $this->addSql(\sprintf(
            "SELECT setval(pg_get_serial_sequence('%1\$s', 'id'), COALESCE((SELECT MAX(id) FROM %1\$s), 0) + 1, false)",
            $table,
        ));
    }

